// Package chunker splits a byte stream into content-defined chunks.
//
// # Why content-defined
//
// Fixed-size chunking cuts every chunk_size bytes from the start of the file,
// so inserting one byte near the beginning shifts every later boundary and the
// whole file has to move again. A content-defined chunker decides where to cut
// from the bytes around the cut point alone, so an insertion changes only the
// chunks it touches and every chunk after it is recognized again.
//
// # The algorithm
//
// FastCDC with normalized chunking, level 2. It was chosen over the older
// Rabin fingerprint for three reasons:
//
//  1. Its rolling hash is a table lookup, a shift and an add per byte, with no
//     multiplication or modulo, so it is several times faster than Rabin at the
//     same chunk size distribution.
//  2. Normalized chunking makes the chunk size distribution far narrower than
//     a plain rolling-hash threshold: a hard mask is used below the average
//     size and an easy one above it, so few chunks end up at the minimum and
//     few are truncated at the maximum. Chunks truncated at the maximum are the
//     ones that do not deduplicate, because their boundary is a position and
//     not content.
//  3. It is a few dozen lines of integer arithmetic, which is what makes the
//     two sides of a transfer agree byte for byte.
//
// Reference: Wen Xia et al., "FastCDC: a Fast and Efficient Content-Defined
// Chunking Approach for Data Deduplication", USENIX ATC 2016.
//
// # Determinism
//
// Both devices must cut a file identically or deduplication finds nothing, so
// nothing here reads a clock, a random source, a map iteration order or a
// machine word size. The gear table is generated by a fixed integer recurrence
// with a fixed seed, the masks are derived from the configured average size,
// and Split produces the same spans whatever sizes the underlying reader
// returns. TestSplit_GoldenCutPoints pins the boundaries of a known input so a
// change to any of that is caught here rather than by a mesh that stops
// deduplicating.
package chunker

import (
	"errors"
	"fmt"
	"io"
	"math/bits"
)

// Chunk size limits. A chunk is one frame payload on the wire and one journal
// row, so the bounds are the protocol's as much as the chunker's.
const (
	// MinSize is the smallest minimum chunk size a configuration may ask
	// for. Below it the rolling hash has too few bytes to look at.
	MinSize = 512
	// MaxSize is the largest maximum chunk size a configuration may ask
	// for. It bounds what one chunk request may make either side buffer.
	MaxSize = 16 << 20
	// DefaultAvg is the average chunk size when none is configured. It is
	// transfer.DefaultChunkSize, repeated rather than imported because a
	// chunker knows nothing about a transfer; the two are checked against
	// each other by TestConfigFor_DefaultMatchesTheTransferDefault.
	DefaultAvg = 64 << 10
)

// ErrConfig reports a chunk size configuration that cannot be used.
var ErrConfig = errors.New("invalid chunker configuration")

// Config is the chunk size distribution: no chunk is shorter than Min except
// the last one, chunks average about Avg, and none is longer than Max.
type Config struct {
	Min, Avg, Max int
}

// ConfigFor returns the configuration for an average chunk size: a minimum of
// a quarter of it and a maximum of four times it, which is the spread FastCDC
// normalized chunking is tuned for. A non-positive average takes DefaultAvg.
func ConfigFor(avg int) Config {
	if avg <= 0 {
		avg = DefaultAvg
	}
	avg = clamp(avg, MinSize*4, MaxSize/4)
	return Config{Min: avg / 4, Avg: avg, Max: avg * 4}
}

// clamp returns v held between lo and hi.
func clamp(v, lo, hi int) int {
	return min(max(v, lo), hi)
}

// Validate reports whether the configuration can be used.
func (c Config) Validate() error {
	switch {
	case c.Min < MinSize:
		return fmt.Errorf("%w: minimum chunk size %d is below %d", ErrConfig, c.Min, MinSize)
	case c.Avg < c.Min:
		return fmt.Errorf("%w: average chunk size %d is below the minimum %d", ErrConfig, c.Avg, c.Min)
	case c.Max < c.Avg:
		return fmt.Errorf("%w: maximum chunk size %d is below the average %d", ErrConfig, c.Max, c.Avg)
	case c.Max > MaxSize:
		return fmt.Errorf("%w: maximum chunk size %d is above %d", ErrConfig, c.Max, MaxSize)
	}
	return nil
}

// Span is one chunk of the stream: where it starts and how long it is.
type Span struct {
	Index  int
	Offset int64
	Length int
}

// Split reads r to EOF and calls emit once per chunk, in order, with the
// chunk's span and its bytes. The bytes are only valid until emit returns:
// they live in the chunker's buffer and the next chunk overwrites them.
//
// A stream of zero bytes produces no chunks, which is how a zero-byte file is
// described: it has no content to ask a peer for.
func Split(r io.Reader, cfg Config, emit func(Span, []byte) error) error {
	if err := cfg.Validate(); err != nil {
		return err
	}
	maskS, maskL := cfg.masks()

	buf := make([]byte, cfg.Max)
	var (
		filled int
		offset int64
		index  int
		eof    bool
	)
	for {
		// The buffer is filled to Max before a cut is looked for, so
		// the cut point never depends on how much the reader happened
		// to return.
		for !eof && filled < len(buf) {
			n, err := r.Read(buf[filled:])
			filled += n
			if err == io.EOF {
				eof = true
				break
			}
			if err != nil {
				return fmt.Errorf("read for chunking: %w", err)
			}
		}
		if filled == 0 {
			return nil
		}
		cut := cfg.cut(buf[:filled], maskS, maskL)
		if err := emit(Span{Index: index, Offset: offset, Length: cut}, buf[:cut]); err != nil {
			return err
		}
		index++
		offset += int64(cut)
		filled = copy(buf, buf[cut:filled])
	}
}

// cut returns the length of the first chunk of data. Split always hands it
// either a full buffer or the end of the stream, so a slice shorter than the
// minimum chunk size is the last chunk and is returned whole.
func (c Config) cut(data []byte, maskS, maskL uint64) int {
	n := len(data)
	if n > c.Max {
		n = c.Max
	}
	if n <= c.Min {
		return n
	}
	// Below the average size the mask is harder to satisfy, above it
	// easier: that is what normalized chunking means, and it is what keeps
	// the chunk sizes close to the average instead of spread over the
	// whole range between the minimum and the maximum.
	normal := c.Avg
	if normal > n {
		normal = n
	}

	var h uint64
	i := c.Min
	for ; i < normal; i++ {
		h = (h << 1) + gear[data[i]]
		if h&maskS == 0 {
			return i + 1
		}
	}
	for ; i < n; i++ {
		h = (h << 1) + gear[data[i]]
		if h&maskL == 0 {
			return i + 1
		}
	}
	return n
}

// masks returns the hard and the easy mask, derived from the average chunk
// size: the hard one has two bits more than the average asks for and the easy
// one two bits fewer, so a cut is four times less likely before the average
// and four times more likely after it.
func (c Config) masks() (maskS, maskL uint64) {
	normalBits := bits.Len(uint(c.Avg)) - 1
	return maskOf(normalBits + 2), maskOf(normalBits - 2)
}

// maskOf returns a mask with n low bits set, held inside 1..63.
func maskOf(n int) uint64 {
	n = clamp(n, 1, 63)
	return 1<<uint(n) - 1
}

// gear is the FastCDC gear table: one 64-bit value per byte value, added to
// the rolling hash as that byte enters the window.
//
// It is generated rather than written out so it can be read: splitmix64 is a
// fixed integer recurrence, so the table is the same on every machine, in
// every build, forever. Changing the seed changes every chunk boundary in
// every folder, so it never changes.
var gear = buildGear(0x3243f6a8885a308d)

// buildGear returns the 256 gear values a seed produces through splitmix64.
func buildGear(seed uint64) [256]uint64 {
	var table [256]uint64
	state := seed
	for i := range table {
		state += 0x9e3779b97f4a7c15
		z := state
		z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
		z = (z ^ (z >> 27)) * 0x94d049bb133111eb
		table[i] = z ^ (z >> 31)
	}
	return table
}
